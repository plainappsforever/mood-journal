// Android backup rules (ported from warranty-wallet D20/D62; Mood SPEC Privacy).
// Google cloud backup (Drive): NOTHING of this app. The database holds the journal (moods, notes) and the
// photos of a private journal; the privacy text promises that the app itself sends nothing, and the owner's own
// backup file is the way to keep or move data. Device-to-device transfer (Android 12+, cable or
// Quick Share during phone setup): everything stays included (no <device-transfer> element = default = all).
// Android 12+ reads data_extraction_rules.xml; Android 11 and older read backup_rules.xml (used there for cloud
// AND device transfer, so both are off on those phones).
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const DOMAINS = ['root', 'file', 'database', 'sharedpref', 'external', 'device_root', 'device_file', 'device_database', 'device_sharedpref'];
const EXCLUDE_ALL = DOMAINS.map((d) => `    <exclude domain="${d}" path="." />`).join('\n');

const DATA_EXTRACTION_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-backup-rules.js (D20, D62): no cloud backup; device transfer = everything. -->
<data-extraction-rules>
  <cloud-backup>
${EXCLUDE_ALL}
  </cloud-backup>
</data-extraction-rules>
`;

const BACKUP_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-backup-rules.js (D20, D62). Android 11 and older: nothing is backed up. -->
<full-backup-content>
${EXCLUDE_ALL}
</full-backup-content>
`;

function withRuleFiles(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'data_extraction_rules.xml'), DATA_EXTRACTION_RULES);
      fs.writeFileSync(path.join(dir, 'backup_rules.xml'), BACKUP_RULES);
      return cfg;
    },
  ]);
}

function withManifestReferences(config) {
  return withAndroidManifest(config, (cfg) => {
    const application = cfg.modResults.manifest.application?.[0];
    if (!application) throw new Error('with-backup-rules: no <application> in AndroidManifest.xml');
    application.$['android:allowBackup'] = 'true';
    application.$['android:dataExtractionRules'] = '@xml/data_extraction_rules';
    application.$['android:fullBackupContent'] = '@xml/backup_rules';
    return cfg;
  });
}

module.exports = function withBackupRules(config) {
  return withManifestReferences(withRuleFiles(config));
};
module.exports.DATA_EXTRACTION_RULES = DATA_EXTRACTION_RULES;
module.exports.BACKUP_RULES = BACKUP_RULES;
